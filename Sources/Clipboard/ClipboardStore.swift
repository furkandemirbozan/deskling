import AppKit
import Combine

/// Panoyu izler ve geçmişi tutar. Yalnızca `changeCount` değişince panoyu okur, bu yüzden boştayken işlemciye yük olmaz.
final class ClipboardStore: ObservableObject {
    @Published private(set) var items: [ClipItem] = []
    @Published var enabled = true { didSet { enabled ? start() : stop() } }
    @Published var limit = 200 { didSet { trim(); scheduleSave() } }

    let pasteboard: NSPasteboard
    let fileURL: URL?
    var frontApp: () -> NSRunningApplication? = { NSWorkspace.shared.frontmostApplication }

    /// Parola yöneticilerinin ve geçici kopyaların işaretleri: bunlar hiç kaydedilmez.
    static let privateTypes: Set<String> = [
        "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword", "de.petermaurer.TransientPasteboardType", "Pasteboard generator type",
        "com.typeit4me.clipping", "net.antelle.keeweb",
    ]
    static let maxText = 100_000
    static let maxRTF = 256 * 1024

    private var lastChange: Int
    private var timer: Timer?
    private var saveWork: DispatchWorkItem?

    init(pasteboard: NSPasteboard = .general, fileURL: URL?) {
        self.pasteboard = pasteboard
        self.fileURL = fileURL
        lastChange = pasteboard.changeCount
        load()
    }

    static var defaultFile: URL {
        FileManager.default.urls(for: .applicationSupportDirectory, in: .userDomainMask)[0]
            .appendingPathComponent("\(AppInfo.name)/pano.json")
    }

    // MARK: - İzleme

    func start() {
        guard enabled, timer == nil else { return }
        lastChange = pasteboard.changeCount   // açılmadan önce kopyalanan şey geçmişe girmez
        let t = Timer(timeInterval: 0.5, repeats: true) { [weak self] _ in self?.poll() }
        t.tolerance = 0.2
        RunLoop.main.add(t, forMode: .common)
        timer = t
    }

    func stop() {
        timer?.invalidate()
        timer = nil
    }

    func poll() {
        let change = pasteboard.changeCount
        guard change != lastChange else { return }
        lastChange = change
        capture()
    }

    private func capture() {
        let types = Set((pasteboard.types ?? []).map(\.rawValue))
        guard types.isDisjoint(with: Self.privateTypes) else { return }
        guard !types.contains(NSPasteboard.PasteboardType.fileURL.rawValue) else { return }   // Finder'da dosya kopyalama
        guard let text = pasteboard.string(forType: .string), !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty,
              text.count <= Self.maxText else { return }
        var rtf = pasteboard.data(forType: .rtf)
        if (rtf?.count ?? 0) > Self.maxRTF { rtf = nil }
        add(text: text, rtf: rtf, app: frontApp())
    }

    /// Aynı metin yeniden kopyalanınca yeni kayıt açılmaz, var olan en üste çıkar.
    func add(text: String, rtf: Data?, app: NSRunningApplication?) {
        var item = ClipItem(text: text, rtf: rtf, kind: ClipClassifier.kind(of: text), date: Date(),
                            appName: app?.localizedName, appBundle: app?.bundleIdentifier, appPath: app?.bundleURL?.path)
        if let i = items.firstIndex(where: { $0.text == text }) {
            let old = items.remove(at: i)
            item.id = old.id
            item.pinned = old.pinned
            if item.rtf == nil { item.rtf = old.rtf }
        }
        items.insert(item, at: 0)
        trim()
        scheduleSave()
    }

    /// Sabitlenenler sınırın dışında tutulur.
    private func trim() {
        var unpinned = 0
        items = items.filter { item in
            if item.pinned { return true }
            unpinned += 1
            return unpinned <= limit
        }
    }

    // MARK: - Düzenleme

    /// Örnek görüntüler için kaynak uygulamayı elle ayarlar.
    func setSource(at i: Int, name: String?, path: String?) {
        guard items.indices.contains(i) else { return }
        items[i].appPath = path
        items[i].appName = name ?? path.map { FileManager.default.displayName(atPath: $0).replacingOccurrences(of: ".app", with: "") }
    }

    func remove(_ item: ClipItem) {
        items.removeAll { $0.id == item.id }
        scheduleSave()
    }

    func togglePin(_ item: ClipItem) {
        guard let i = items.firstIndex(where: { $0.id == item.id }) else { return }
        items[i].pinned.toggle()
        scheduleSave()
    }

    func clear(keepPinned: Bool = true) {
        items = keepPinned ? items.filter(\.pinned) : []
        scheduleSave()
    }

    /// Kaydı panoya yazar. Düz metin seçilirse biçimlendirme bırakılır. Kayıt en üste çıkar.
    func write(_ item: ClipItem, plain: Bool) {
        pasteboard.clearContents()
        if !plain, let rtf = item.rtf { pasteboard.setData(rtf, forType: .rtf) }
        pasteboard.setString(item.text, forType: .string)
        lastChange = pasteboard.changeCount   // kendi yazdığımızı yeniden kaydetmeyelim
        if let i = items.firstIndex(where: { $0.id == item.id }) {
            var moved = items.remove(at: i)
            moved.date = Date()
            items.insert(moved, at: 0)
            scheduleSave()
        }
    }

    /// Renk ya da başka bir biçime çevrilmiş metni yazar (örneğin HEX yerine RGB).
    func writeText(_ text: String) {
        pasteboard.clearContents()
        pasteboard.setString(text, forType: .string)
        lastChange = pasteboard.changeCount
    }

    // MARK: - Kayıt

    private func load() {
        guard let fileURL, let data = try? Data(contentsOf: fileURL),
              let list = try? JSONDecoder().decode([ClipItem].self, from: data) else { return }
        items = list
    }

    private func scheduleSave() {
        guard fileURL != nil else { return }
        saveWork?.cancel()
        let work = DispatchWorkItem { [weak self] in self?.save() }
        saveWork = work
        DispatchQueue.main.asyncAfter(deadline: .now() + 1, execute: work)
    }

    /// Geçmiş yalnızca bu kullanıcının okuyabildiği bir dosyaya yazılır.
    func save() {
        guard let fileURL, let data = try? JSONEncoder().encode(items) else { return }
        let fm = FileManager.default
        try? fm.createDirectory(at: fileURL.deletingLastPathComponent(), withIntermediateDirectories: true)
        try? data.write(to: fileURL, options: .atomic)
        try? fm.setAttributes([.posixPermissions: 0o600], ofItemAtPath: fileURL.path)
    }
}
